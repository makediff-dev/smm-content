function createSeedContent(
  id: string,
  projectId: string,
  title: string,
  format: ContentFormat,
  overrides: Partial<ContentUnit> = {}
): ContentUnit {
  return {
    id,
    projectId,
    title,
    format,
    formatConfirmed: true,
    sourceType: "url",
    sourceUrl: `https://example.com/${id}`,
    sourceFileName: "",
    sourceUseLink: true,
    sourceUseFile: false,
    sourceNotesEnabled: false,
    sourceNotes: "",
    sourceFiles: [],
    sourceExtracts: {},
    cardsCount: 3,
    videoTransition: "none",
    status: "draft",
    createdAt: daysAgo(1),
    cards: [],
    postText: "",
    promptId: "prompt-post",
    extractedTitle: "",
    extractedText: "",
    extractedImages: [],
    additionalInstructions: "",
    voiceModel: "default",
    speechSpeed: 1,
    narrationText: "",
    actionLog: [],
    buildOptions: {
      addCopyright: true,
      applyBrandStyle: true,
      prepareArchive: true,
    },
    textTone: "friendly",
    textLength: "medium",
    textOptions: {
      includeHashtags: true,
      includeEmoji: false,
      addSourceLink: true,
    },
    generationPrompt: "",
    ...overrides,
    sourceLinks:
      overrides.sourceLinks ??
      [overrides.sourceUrl ?? `https://example.com/${id}`],
  };
}

